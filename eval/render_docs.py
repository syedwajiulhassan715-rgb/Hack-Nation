"""Write the generated metrics block into README.md and METHOD.md (CLAUDE.md golden rule 14).

Everything between `<!-- metrics:begin -->` and `<!-- metrics:end -->` is replaced on every
`python -m navigator eval` run from the eval metrics and the output files. Nothing in that
block is typed by hand; prose outside it carries no measured numbers.
"""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

from navigator import settings

BEGIN, END = "<!-- metrics:begin -->", "<!-- metrics:end -->"
DOCS = ("README.md", "METHOD.md")
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def _ratio(m: Any) -> str:
    if isinstance(m, dict) and m.get("den"):
        return f"{m['num']}/{m['den']} ({100 * m['num'] / m['den']:.0f}%)"
    return "n/a"


def _load(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def render(metrics: dict[str, Any], header: dict[str, Any], out_dir: Path) -> str:
    lookups = _load(out_dir / "lookups.json") or {}
    results = Counter(r["result"] for rows in (lookups.get("lookups") or {}).values() for r in rows)
    flagged = sum(r["conflict_flag"] for rows in (lookups.get("lookups") or {}).values() for r in rows)
    summaries = (_load(out_dir / "summaries.json") or {}).get("summaries") or {}
    changes = _load(out_dir / "changes.json") or {}
    cc = metrics.get("change_checks") or {}

    lines = [
        BEGIN,
        f"_Generated by `python -m navigator eval` at {header['ts']} (commit {header['commit']}). "
        "Self-evaluation with our own harness; the pack has no official scoring script._",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Hard checks (format, grounding) | {'FAIL' if header['hard_fail'] else 'PASS'} |",
        f"| Rules extracted | {metrics.get('rules_total', 'n/a')} "
        f"({', '.join(f'{k} {v}' for k, v in sorted((metrics.get('rules_by_status') or {}).items()))}) |",
        f"| Rule records valid against the official schema | {_ratio(metrics.get('rules_schema_valid'))} |",
        f"| Quotes found verbatim in the source document | {_ratio(metrics.get('grounding_span_found'))} |",
        f"| source_url equals the manifest url | {_ratio(metrics.get('grounding_source_url'))} |",
        f"| Laws named in the briefs found (with text in corpus) | {_ratio(metrics.get('checklist_recall'))} |",
        f"| Addresses covered in lookups.json | {_ratio(metrics.get('lookups_cover_all'))} |",
        f"| Lookup rows | {metrics.get('lookup_rows_total', 'n/a')} "
        f"({', '.join(f'{k} {v}' for k, v in sorted(results.items()))}); conflict-flagged {flagged} |",
        f"| Change-test assertions (T1-T5) | {cc.get('pass', 'n/a')} pass, {cc.get('fail', 'n/a')} fail, "
        f"{cc.get('not_checkable', 'n/a')} not checkable (no source text) |",
    ]
    for tid, v in sorted(changes.items()):
        lines.append(f"| {tid} affected / conflict-flagged addresses | "
                     f"{len(v['affected_address_ids'])} / {len(v['conflict_flag_address_ids'])} |")
    if summaries:
        kept_t = sum(1 for s in summaries.values() if s.get("answer_tenant"))
        kept_o = sum(1 for s in summaries.values() if s.get("answer_owner"))
        lines.append(f"| Plain-language answers kept after guards (tenant / owner) | "
                     f"{kept_t}/{len(summaries)} / {kept_o}/{len(summaries)} |")
    lines += ["", "Full report: `scores/eval_latest.txt`; change tests: `scores/changes_report.txt`.", END]
    return "\n".join(lines)


def update(metrics: dict[str, Any], header: dict[str, Any], out_dir: Path) -> list[str]:
    """Rewrite the block in each doc that has the markers; returns the files changed."""
    block = render(metrics, header, out_dir)
    changed = []
    for name in DOCS:
        path = settings.REPO_ROOT / name
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if BEGIN not in text:
            continue
        new = BLOCK.sub(lambda _: block, text)
        if new != text:
            path.write_text(new, encoding="utf-8", newline="\n")
            changed.append(name)
    return changed
