"""Human review checklist for the draft gold set -> eval/REVIEW_CHECKLIST.md.

    python -m eval.review_checklist

For each gold rule: the expected fields next to the anchor quote *in its source document*
(with surrounding text), so a reviewer can tick it off without hunting through the corpus.
For each gold address: the CSV row, a Census Geocoder link for the legal city, and the
expected results with the gold author's reason.

Reads only eval/gold/, the corpus text and the address CSV. Never reads outputs/ (the
reviewer checks the gold set against the law, not against our answers). Not legal advice.
"""
from __future__ import annotations

import csv
from pathlib import Path
from urllib.parse import urlencode

from eval.gold_eval import _default_body_of, load_gold, locate

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).parent / "REVIEW_CHECKLIST.md"
ADDRESS_CSV = ROOT / "data" / "starter" / "data" / "sample_addresses.csv"
CONTEXT = 320  # characters of document text shown on each side of the anchor
CONF_ORDER = {"low": 0, "medium": 1, "high": 2}
CENSUS = "https://geocoding.geo.census.gov/geocoder/geographies/onelineaddress"


def _excerpt(body: str | None, anchor: str) -> str:
    """Anchor in context, the anchor itself in bold; or a loud 'not found'."""
    if body is None:
        return "> **Source document has no text in the corpus.**"
    loc = locate(anchor, body)
    if loc is None:
        return "> **ANCHOR NOT FOUND in the source text: fix `anchor_quote` or `source_doc_id`.**"
    s, e = loc
    a, b = max(0, s - CONTEXT), min(len(body), e + CONTEXT)
    pre = ("…" if a > 0 else "") + body[a:s]
    post = body[e:b] + ("…" if b < len(body) else "")
    return "> " + pre + "**" + body[s:e] + "**" + post


def _census_link(row: dict) -> str:
    q = urlencode({
        "address": f"{row['street_address']}, {row['postal_city']}, {row['state']} {row['zip']}",
        "benchmark": "Public_AR_Current",
        "vintage": "Current_Current",
        "format": "html",
    })
    return f"{CENSUS}?{q}"


def build() -> str:
    rules_doc, addr_doc = load_gold()
    if rules_doc is None or addr_doc is None:
        raise SystemExit("eval/gold/rules.yaml or addresses.yaml is missing")
    body_of = _default_body_of()
    with ADDRESS_CSV.open(encoding="utf-8", newline="") as fh:
        csv_rows = {r["address_id"]: r for r in csv.DictReader(fh)}
    gold_rules = {g["id"]: g for g in rules_doc.get("rules", [])}

    out = [
        "# Gold set review checklist",
        "",
        "Generated by `python -m eval.review_checklist` from `eval/gold/` and the corpus text.",
        "Do not edit this file; edit the YAML files and regenerate. Not legal advice.",
        "",
        "**How to review.** For every entry, read the source text and tick the box only if the",
        "expectation follows from the law text. If it does not, fix the entry in",
        "`eval/gold/*.yaml` (never to make our numbers look better: the gold set must say what",
        "the law says). When a file is fully reviewed, set `reviewed_by` and `reviewed_at` at",
        "its top, then run `python -m navigator eval`.",
        "",
        "Rules are sorted by the author's confidence, lowest first: check those most carefully.",
        "",
        f"## Part 1: rules (`eval/gold/rules.yaml`, {len(gold_rules)} entries)",
        "",
    ]
    rules_sorted = sorted(gold_rules.values(), key=lambda g: (CONF_ORDER.get(g.get("confidence"), 0), g["id"]))
    for g in rules_sorted:
        out += [
            f"### [ ] `{g['id']}` · {g['jurisdiction']} · {g['category']} · confidence {g.get('confidence', '?')}",
            "",
            "| Field | Expected |",
            "|---|---|",
            f"| level | {g.get('level')} |",
            f"| status on {rules_doc.get('as_of')} | {g.get('status')} |",
            f"| effective_date | {g.get('effective_date')} |",
        ]
        if g.get("also_ok"):
            out.append(f"| also acceptable | {g['also_ok']} |")
        if g.get("key_value"):
            out.append(f"| key value | {g['key_value']} |")
        out += [
            f"| source | {g['source_doc_id']} |",
            "",
            f"Author's basis: {g.get('basis', '(none)')}",
            "",
            _excerpt(body_of(g["source_doc_id"]), g["anchor_quote"]),
            "",
        ]
        for extra in g.get("also_match") or []:
            out += [f"Also stated in {extra['source_doc_id']}:", "",
                    _excerpt(body_of(extra["source_doc_id"]), extra["anchor_quote"]), ""]

    addresses = addr_doc.get("addresses", [])
    out += [f"## Part 2: addresses (`eval/gold/addresses.yaml`, {len(addresses)} entries)", "",
            "First confirm the legal city with the Census link (look at *Incorporated Places* /",
            "*County Subdivisions*, not the postal city), then each expected result against the",
            "rule's conditions in Part 1.", ""]
    for a in addresses:
        row = csv_rows.get(a["address_id"])
        out.append(f"### `{a['address_id']}` · expected legal city: {a.get('legal_city')}")
        out.append("")
        if row:
            out += [
                f"- Address: {row['street_address']}, {row['postal_city']}, {row['state']} {row['zip']}",
                f"- CSV facts: year built `{row['year_built'] or '(missing)'}` · units `{row['units'] or '(missing)'}`"
                f" · use `{row['use_description'] or '(missing)'}`",
                f"- [ ] Legal city confirmed: [Census Geocoder]({_census_link(row)})",
            ]
        else:
            out.append("- **Address id not in the CSV: fix the entry.**")
        if a.get("city_reason"):
            out.append(f"- Author's city note: {a['city_reason']}")
        for r in a.get("results", []):
            g = gold_rules.get(r["rule"])
            where = f"{g['jurisdiction']} {g['category']}" if g else "UNKNOWN GOLD RULE"
            alt = f" (also ok: {', '.join(r['also_ok'])})" if r.get("also_ok") else ""
            out.append(f"- [ ] `{r['rule']}` ({where}) → **{r['expected']}**{alt} — {r.get('reason', '')}")
        out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}. Not legal advice.")


if __name__ == "__main__":
    main()
