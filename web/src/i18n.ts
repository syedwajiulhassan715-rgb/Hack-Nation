export const STRINGS: Record<Lang, Strings> = { en: EN, es: ES }

export interface LangState {
  lang: Lang
  setLang: (l: Lang) => void
}

export const LangContext = createContext<LangState>({ lang: 'en', setLang: () => {} })

export function useI18n(): LangState & { t: Strings } {
  const s = useContext(LangContext)
  return { ...s, t: STRINGS[s.lang] }
}

const KEY = 'navigator.lang'

/** ?lang=es wins, then the saved choice, then English. */
export function initialLang(): Lang {
  if (typeof window === 'undefined') return 'en'
  const q = new URLSearchParams(window.location.search).get('lang')
  if (q === 'es' || q === 'en') return q
  try {
    const saved = window.localStorage.getItem(KEY)
    if (saved === 'es' || saved === 'en') return saved
  } catch {
    /* storage blocked */
  }
  return 'en'
}

export function saveLang(l: Lang) {
  try {
    window.localStorage.setItem(KEY, l)
  } catch {
    /* storage blocked */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = l
}
